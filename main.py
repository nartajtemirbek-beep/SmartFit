def uid(request):
    user=request.session.get('uid')
    if user is None:return None
    with db() as c:
        exists=c.execute('SELECT id FROM accounts WHERE id=?',(user,)).fetchone()
    if not exists:
        request.session.clear()
        return None
    return user

