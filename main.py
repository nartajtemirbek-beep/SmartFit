class PgConnection:
    """Small adapter so the existing SQLite-style parameterized queries work in PostgreSQL."""
    def __init__(self, connection):
        self.connection = connection

    def execute(self, sql, params=()):
        # psycopg uses %s bind placeholders; SQLite uses ?.
        is_insert = sql.lstrip().upper().startswith('INSERT INTO ')
        inserted_key = None
        if is_insert and 'RETURNING ' not in sql.upper():
            # Only INSERT statements need a generated primary key. Never consume SELECT rows.
            inserted_key = 'user_id' if sql.lstrip().upper().startswith('INSERT INTO PROFILES') else 'id'
            sql = sql.rstrip().rstrip(';') + ' RETURNING ' + inserted_key
        cur = self.connection.execute(sql.replace('?', '%s'), params)
        return PgResult(cur, inserted_key)

class PgResult:
    def __init__(self, cur, inserted_key=None):
        self.cur = cur
        self.lastrowid = None
        if inserted_key is not None:
            row = cur.fetchone()
            self.lastrowid = row[inserted_key] if row is not None else None

    def fetchone(self):
        return self.cur.fetchone()

    def fetchall(self):
        return self.cur.fetchall()

@contextmanager
def db():
    if USE_POSTGRES:
        import psycopg
        from psycopg.rows import dict_row
        with psycopg.connect(DATABASE_URL, row_factory=dict_row, connect_timeout=10) as connection:
            yield PgConnection(connection)
    else:
        con=sqlite3.connect(DB_PATH,timeout=20)
        con.row_factory=sqlite3.Row
        con.execute('PRAGMA foreign_keys=ON')
        try:
            yield con;con.commit()
        finally:con.close()

